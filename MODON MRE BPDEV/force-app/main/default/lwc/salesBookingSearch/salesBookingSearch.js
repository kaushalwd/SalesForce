handleUploadBCCLetter() {

    const selectedIds = [...this.selectedRowIds];

    if (!selectedIds.length) {
        this.showToast(
            'Warning',
            'Please select at least one Business Process.',
            'warning'
        );
        return;
    }

    // First selected BP is the temporary upload location
    this.bccUploadRecordId = selectedIds[0];

    this.bccUploadedFileName = null;
    this.showBCCLetterModal = true;
}

async handleBCCUploadFinished(event) {

    const uploadedFiles = event.detail.files;

    if (!uploadedFiles || uploadedFiles.length === 0) {
        this.showToast(
            'Error',
            'No file was uploaded.',
            'error'
        );
        return;
    }

    const contentDocumentId = uploadedFiles[0].documentId;

    const selectedIds = [...this.selectedRowIds];

    this.bccUploadedFileName = uploadedFiles[0].name;

    this.isLoading = true;

    try {

        const response = await uploadBCCLetter({
            businessProcessIds: selectedIds,
            contentDocumentId: contentDocumentId
        });

        if (response.success) {

            this.showToast(
                'Success',
                response.message,
                'success'
            );

            this.showBCCLetterModal = false;
            this.bccUploadRecordId = null;
            this.bccUploadedFileName = null;

            this.handleClear();

        } else {

            this.showToast(
                'Error',
                response.message,
                'error'
            );
        }

    } catch (error) {

        console.error('BCC Letter Upload Error:', error);

        this.showToast(
            'Error',
            error?.body?.message ||
            'Unable to upload BCC Letter.',
            'error'
        );

    } finally {

        this.isLoading = false;
    }
}

handleCloseBCCLetterModal() {

    if (this.isLoading) {
        return;
    }

    this.showBCCLetterModal = false;

    this.bccUploadRecordId = null;

    this.bccUploadedFileName = null;
}

