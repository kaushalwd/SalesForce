async handleCsvFileChange(event) {

    const file = event.target.files[0];

    if (!file) {
        return;
    }

    if (!file.name.toLowerCase().endsWith('.csv')) {

        this.showToast(
            'Invalid File',
            'Please upload a CSV file only.',
            'error'
        );

        return;
    }

    this.isLoading = true;

    try {

        const csvText = await this.readCsvFile(file);

        const unitNames = this.parseUnitNamesFromCsv(csvText);

        if (!unitNames || unitNames.length === 0) {

            this.showToast(
                'Invalid CSV',
                'No Unit Name values were found in the CSV file.',
                'warning'
            );

            return;
        }

        console.log(
            'CSV Unit Names:',
            JSON.stringify(unitNames)
        );

        this.csvTotalUnits = unitNames.length;

        const result = await getBusinessProcessByUnitNames({
            unitNames: unitNames
        });

        console.log(
            'CSV Search Result:',
            JSON.stringify(result)
        );

        this.processCsvResult(result);

    } catch (error) {

        console.error(
            'CSV Upload Error:',
            error
        );

        this.showToast(
            'Error',
            error?.body?.message ||
            'An error occurred while processing the CSV file.',
            'error'
        );

    } finally {

        this.isLoading = false;

        /*
         * Clear file input so the same file can be uploaded again.
         */
        event.target.value = null;
    }
}

readCsvFile(file) {

    return new Promise((resolve, reject) => {

        const reader = new FileReader();

        reader.onload = () => {
            resolve(reader.result);
        };

        reader.onerror = () => {
            reject(
                new Error('Unable to read CSV file.')
            );
        };

        reader.readAsText(file);
    });
}

parseUnitNamesFromCsv(csvText) {

    if (!csvText) {
        return [];
    }

    /*
     * Remove BOM if present.
     */
    csvText = csvText.replace(/^\uFEFF/, '');

    const lines = csvText
        .split(/\r?\n/)
        .map(line => line.trim())
        .filter(line => line.length > 0);

    if (lines.length < 2) {
        return [];
    }

    const headers = this.parseCsvLine(lines[0]);

    const normalizedHeaders = headers.map(header =>
        header
            .trim()
            .replace(/^["']|["']$/g, '')
            .toLowerCase()
            .replace(/\s+/g, '')
    );

    const unitNameIndex = normalizedHeaders.findIndex(
        header =>
            header === 'unitname' ||
            header === 'unit'
    );

    if (unitNameIndex === -1) {

        this.showToast(
            'Invalid CSV',
            'CSV must contain a "Unit Name" column.',
            'error'
        );

        return [];
    }

    const unitNames = [];

    for (let i = 1; i < lines.length; i++) {

        const values = this.parseCsvLine(lines[i]);

        if (
            values.length <= unitNameIndex
        ) {
            continue;
        }

        let unitName = values[unitNameIndex];

        if (!unitName) {
            continue;
        }

        unitName = unitName
            .trim()
            .replace(/^["']|["']$/g, '')
            .trim();

        if (unitName) {
            unitNames.push(unitName);
        }
    }

    /*
     * Remove duplicates while preserving order.
     */
    return [
        ...new Set(unitNames)
    ];
}

parseCsvLine(line) {

    const result = [];

    let current = '';
    let insideQuotes = false;

    for (let i = 0; i < line.length; i++) {

        const char = line[i];

        if (char === '"') {

            if (
                insideQuotes &&
                line[i + 1] === '"'
            ) {

                current += '"';
                i++;

            } else {

                insideQuotes = !insideQuotes;
            }

        } else if (
            char === ',' &&
            !insideQuotes
        ) {

            result.push(current);
            current = '';

        } else {

            current += char;
        }
    }

    result.push(current);

    return result;
}

processCsvResult(result) {

    const returnedRecords =
        result?.records || [];

    const missingUnits =
        result?.missingUnitNames || [];

    /*
     * =====================================================
     * STORE MISSING UNIT NAMES
     * =====================================================
     */

    this.missingUnitNames = [
        ...missingUnits
    ];

    /*
     * =====================================================
     * STORE FOUND RECORDS
     * =====================================================
     */

    this.allRecords = returnedRecords.map(row => ({
        ...row,
        isChecked: false
    }));

    this.csvFoundUnits =
        result?.foundUnitCount ||
        this.allRecords.length;

    /*
     * =====================================================
     * CSV SEARCH MODE
     * =====================================================
     */

    this.isCsvSearch = true;

    /*
     * Use the same columns returned by Apex.
     */
    this.columns = result?.columns || [];

    /*
     * =====================================================
     * PAGINATION
     * =====================================================
     */

    this.pageNumber = 1;

    if (this.allRecords.length > 0) {

        this.totalPages = Math.ceil(
            this.allRecords.length /
            this.pageSize
        );

        this.updatePageData();

        this.showTable = true;
        this.showNoRecords = false;

    } else {

        this.records = [];
        this.totalPages = 0;
        this.showTable = false;
        this.showNoRecords = true;
    }

    /*
     * =====================================================
     * MESSAGE
     * =====================================================
     */

    if (
        this.allRecords.length > 0 &&
        this.missingUnitNames.length > 0
    ) {

        this.showToast(
            'Completed',
            `${this.csvFoundUnits} unit(s) found. ` +
            `${this.missingUnitNames.length} unit(s) not found.`,
            'warning'
        );

    } else if (
        this.allRecords.length > 0
    ) {

        this.showToast(
            'Success',
            `${this.csvFoundUnits} unit(s) found.`,
            'success'
        );

    } else {

        this.showToast(
            'No Records',
            'No Business Process / Handover records were found for the uploaded Unit Names.',
            'warning'
        );
    }
}

