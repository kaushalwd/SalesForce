        const selectedIds = new Set(
            event.detail.selectedRows.map(row => row.Id)
        );

        console.log(
            'USER SELECTED ON PAGE:',
            this.pageNumber,
            JSON.stringify([...selectedIds])
        );

        /*
         * Update isChecked ONLY for records on the current page.
         *
         * Records on other pages remain untouched.
         */
        const currentPageIds = new Set(
            this.records.map(row => row.Id)
        );

        this.allRecords = this.allRecords.map(row => {

            if (currentPageIds.has(row.Id)) {

                return {
                    ...row,
                    isChecked: selectedIds.has(row.Id)
                };
            }

            return row;
        });

        /*
         * Refresh current page references.
         */
        const start = (this.pageNumber - 1) * this.pageSize;
        const end = start + this.pageSize;

        this.records = this.allRecords.slice(start, end);

        console.log(
            'CURRENT PAGE isChecked:',
            JSON.stringify(
                this.records.map(row => ({
                    Id: row.Id,
                    isChecked: row.isChecked
                }))
            )
        );

