async handleUpdatePhasingSave() {

    if (!this.selectedZone) {

        this.showToast(
            'Validation',
            'Please select a Zone.',
            'warning'
        );

        return;
    }

    const selectedIds = [...this.selectedRowIds];

    if (!selectedIds.length) {

        this.showToast(
            'Validation',
            'Please select at least one Unit.',
            'warning'
        );

        return;
    }

    this.isLoading = true;

    try {

        const response = await updateHandoverDetailZone({
            businessProcessIds: selectedIds,
            zoneName: this.selectedZone
        });

        if (response.success) {

            this.showToast(
                'Success',
                response.message,
                'success'
            );

            /*
             * Remove successfully updated records
             * from the CSV table.
             */
            this.removeUpdatedCsvRecords(selectedIds);

            /*
             * Close modal.
             */
            this.showUpdatePhasingModal = false;
            this.selectedZone = '';

        } else {

            this.showToast(
                'Error',
                response.message,
                'error'
            );
        }

    } catch (error) {

        console.error(
            'Update Phasing Error:',
            error
        );

        this.showToast(
            'Error',
            error?.body?.message ||
            'Unable to update the Handover Detail.',
            'error'
        );

    } finally {

        this.isLoading = false;
    }
}

removeUpdatedCsvRecords(updatedIds) {

    const updatedIdSet = new Set(updatedIds);

    /*
     * Remove from all records.
     */
    this.allRecords = this.allRecords.filter(
        row => !updatedIdSet.has(row.Id)
    );

    /*
     * Recalculate pagination.
     */
    if (this.allRecords.length > 0) {

        this.totalPages = Math.ceil(
            this.allRecords.length / this.pageSize
        );

        /*
         * If the current page no longer exists,
         * move back to the last available page.
         */
        if (this.pageNumber > this.totalPages) {

            this.pageNumber = this.totalPages;
        }

        this.updatePageData();

        this.showTable = true;
        this.showNoRecords = false;

    } else {

        this.records = [];
        this.totalPages = 0;
        this.pageNumber = 1;

        this.showTable = false;
        this.showNoRecords = true;
    }
}

